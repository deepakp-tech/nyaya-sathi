"""Verified legal corpus: loading + hybrid retrieval (vector + keyword).

The corpus is the ONLY source of law the assistant may cite.
"""
import json
import math
import re
from collections import Counter
from functools import lru_cache

from app import config

TOKEN = re.compile(r"[a-z0-9]+")


def _tokens(text: str) -> list[str]:
    return TOKEN.findall(text.lower())


@lru_cache(maxsize=1)
def load_corpus() -> dict[str, dict]:
    """Return {id: entry} for statute sections + playbooks."""
    corpus: dict[str, dict] = {}
    with open(config.CORPUS_FILE, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                e = json.loads(line)
                e["kind"] = "section"
                corpus[e["id"]] = e
    for p in sorted(config.PLAYBOOK_DIR.glob("*.md")):
        raw = p.read_text(encoding="utf-8")
        meta, body = _split_front_matter(raw)
        corpus[meta["id"]] = {
            "id": meta["id"],
            "kind": "playbook",
            "act": "Practical guide",
            "section": "",
            "title": meta.get("title", p.stem),
            "summary": body.strip(),
            "topics": meta.get("topics", []),
            "related": meta.get("related", []),
            "status": "guide",
            "verified": True,  # written by us from official procedure pages
        }
    return corpus


def _split_front_matter(raw: str) -> tuple[dict, str]:
    if not raw.startswith("---"):
        return {}, raw
    _, fm, body = raw.split("---", 2)
    meta = {}
    for line in fm.strip().splitlines():
        k, _, v = line.partition(":")
        v = v.strip()
        if v.startswith("[") and v.endswith("]"):
            v = [x.strip() for x in v[1:-1].split(",") if x.strip()]
        meta[k.strip()] = v
    return meta, body


def entry_text(e: dict) -> str:
    head = f"{e['act']} {('Section ' + e['section']) if e.get('section') else ''} — {e['title']}"
    return f"{head}\n{e['summary']}\nTopics: {', '.join(e.get('topics', []))}"


def human_ref(e: dict) -> str:
    """How a citation is shown to the user. Generated by code, never by the LLM."""
    if e["kind"] == "playbook":
        return f"Guide: {e['title']}"
    sec = e.get("section", "")
    if sec and sec[0].isdigit():
        return f"{e['act']}, Section {sec}"
    return f"{e['act']} ({sec})" if sec else e["act"]


# ---------------------------------------------------------------- vector index
@lru_cache(maxsize=1)
def _vector_store():
    """Chroma store; returns None if embeddings are unavailable (keyword-only fallback)."""
    try:
        from langchain_chroma import Chroma
        from langchain_huggingface import HuggingFaceEmbeddings
    except ImportError:
        return None
    emb = HuggingFaceEmbeddings(model_name=config.EMBEDDING_MODEL)
    vs = Chroma(collection_name="legal_corpus", embedding_function=emb,
                persist_directory=config.CHROMA_DIR)
    # Fresh deployments (e.g. Streamlit Cloud) start without .chroma/: build the index once on first use.
    try:
        if not vs.get(limit=1)["ids"]:
            _populate(vs)
    except Exception:  # noqa: BLE001 - retrieval falls back to keyword search
        pass
    return vs


def _populate(vs) -> int:
    from langchain_core.documents import Document
    corpus = load_corpus()
    docs = [Document(page_content=entry_text(e), metadata={"id": e["id"]}) for e in corpus.values()]
    vs.add_documents(docs, ids=[d.metadata["id"] for d in docs])
    return len(docs)


def build_index() -> int:
    """(Re)build the vector index from the corpus. Run via scripts/ingest.py."""
    vs = _vector_store()
    if vs is None:
        raise RuntimeError("langchain-chroma / langchain-huggingface not installed")
    try:
        existing = vs.get()["ids"]
        if existing:
            vs.delete(ids=existing)
    except Exception:
        pass
    return _populate(vs)


# ---------------------------------------------------------------- retrieval
def _keyword_scores(query: str) -> dict[str, float]:
    corpus = load_corpus()
    q = Counter(_tokens(query))
    n = len(corpus)
    df = Counter()
    toks = {}
    for cid, e in corpus.items():
        t = set(_tokens(entry_text(e)))
        toks[cid] = t
        df.update(t)
    scores = {}
    for cid, t in toks.items():
        s = sum(math.log(1 + n / df[w]) for w in q if w in t)
        if s > 0:
            scores[cid] = s
    return scores


def retrieve(query: str, category: str | None = None, k: int | None = None) -> list[dict]:
    """Hybrid retrieval with topic boost; playbooks pull in their related sections."""
    k = k or config.RETRIEVAL_K
    corpus = load_corpus()
    scores: dict[str, float] = {}

    kw = _keyword_scores(query)
    if kw:
        mx = max(kw.values())
        for cid, s in kw.items():
            scores[cid] = scores.get(cid, 0) + s / mx

    vs = None
    try:
        vs = _vector_store()
    except Exception:
        vs = None
    if vs is not None:
        try:
            for rank, (doc, _) in enumerate(vs.similarity_search_with_score(query, k=k * 2)):
                cid = doc.metadata.get("id")
                if cid in corpus:
                    scores[cid] = scores.get(cid, 0) + 1.0 / (1 + rank * 0.5)
        except Exception:
            pass  # index not built yet -> keyword only

    topic_map = {"tenancy": "tenancy", "consumer": "consumer", "employment": "salary"}
    if category in topic_map:
        for cid, e in corpus.items():
            if topic_map[category] in e.get("topics", []):
                scores[cid] = scores.get(cid, 0) + 0.6

    ranked = [cid for cid, _ in sorted(scores.items(), key=lambda x: -x[1])][:k]
    # expand playbooks with their related sections (bounded)
    out, seen = [], set()
    for cid in ranked:
        for x in [cid] + corpus[cid].get("related", []):
            if x in corpus and x not in seen and len(out) < k + 6:
                seen.add(x)
                out.append(corpus[x])
    return out


def format_sources(entries: list[dict]) -> str:
    """Sources block given to the LLM. Each entry is addressed only by its ID."""
    blocks = []
    for e in entries:
        flag = "" if e.get("verified") else " [status: pending human verification]"
        if e.get("status") in ("model_law", "check_current"):
            flag += f" [note: {e['status']}]"
        blocks.append(f"<source id=\"{e['id']}\">{flag}\n{entry_text(e)}\n</source>")
    return "\n".join(blocks)
